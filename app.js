const languageButtons = document.querySelectorAll('[data-language]');
const i18nNodes = document.querySelectorAll('[data-i18n]');

function preferredLanguage() {
  let stored = null;
  try {
    stored = localStorage.getItem('jetsiv-language');
  } catch {
    // Browsers with storage disabled fall back to their preferred language.
  }
  if (stored === 'zh' || stored === 'en') return stored;
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

function applyLanguage(language) {
  const messages = translations[language];
  if (!messages) return;

  document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
  document.title = document.body.classList.contains('legal-page')
    ? `${messages.privacyTitle} — Jetsiv Labs`
    : messages.documentTitle;

  i18nNodes.forEach((node) => {
    const value = messages[node.dataset.i18n];
    if (value !== undefined) node.innerHTML = value;
  });

  languageButtons.forEach((button) => {
    const isZh = language === 'zh';
    const zh = button.querySelector('span:first-child');
    const en = button.querySelector('span:last-child');
    if (zh && en) {
      zh.classList.toggle('language-active', isZh);
      en.classList.toggle('language-active', !isZh);
    }
    button.setAttribute('aria-label', isZh ? 'Switch to English' : '切换为中文');
  });

  try {
    localStorage.setItem('jetsiv-language', language);
  } catch {
    // Language switching still works for the current page without persistence.
  }
}

applyLanguage(preferredLanguage());

languageButtons.forEach((button) => {
  button.addEventListener('click', () => {
    applyLanguage(document.documentElement.lang.startsWith('zh') ? 'en' : 'zh');
  });
});

const navToggle = document.querySelector('[data-nav-toggle]');
const nav = document.querySelector('[data-nav]');

function closeNavigation() {
  if (!navToggle || !nav) return;
  navToggle.setAttribute('aria-expanded', 'false');
  nav.classList.remove('is-open');
  document.body.classList.remove('nav-open');
}

if (navToggle && nav) {
  navToggle.addEventListener('click', () => {
    const open = navToggle.getAttribute('aria-expanded') !== 'true';
    navToggle.setAttribute('aria-expanded', String(open));
    nav.classList.toggle('is-open', open);
    document.body.classList.toggle('nav-open', open);
  });

  nav.querySelectorAll('a').forEach((link) => link.addEventListener('click', closeNavigation));
  window.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') closeNavigation();
  });
  window.addEventListener('resize', () => {
    if (window.innerWidth > 900) closeNavigation();
  });
}

const header = document.querySelector('[data-header]');
if (header && !header.classList.contains('header-solid')) {
  const updateHeader = () => header.classList.toggle('is-scrolled', window.scrollY > 24);
  updateHeader();
  window.addEventListener('scroll', updateHeader, { passive: true });
}
